import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const result = await build({
  entryPoints: [fileURLToPath(new URL('../src/server.ts', import.meta.url))],
  outfile: fileURLToPath(new URL('../dist/server.js', import.meta.url)),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: ['node20'],
  sourcemap: true,
  minify: false,
  packages: 'bundle',
  banner: {
    js: '#!/usr/bin/env node\n// Generated by apps/server/scripts/build.mjs - do not edit; edit src/ instead.',
  },
  logLevel: 'info',
  metafile: true,
});

const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
console.log(`dist/server.js written (${(bytes / 1024).toFixed(1)} kB, self-contained)`);