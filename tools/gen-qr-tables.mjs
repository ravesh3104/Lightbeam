/**
 * gen-qr-tables.mjs
 * ---------------------------------------------------------------------------
 * Generates `packages/core/src/qr/tables.ts` for the LightBeam QR encoder.
 *
 * Why generate tables instead of hand-writing them?
 *   - Hand-typed Reed-Solomon block tables are the classic source of "works for
 *     small QRs, breaks at version 27" bugs.
 *   - We derive them at build time from the battle-tested `qrcode` package and
 *     freeze the result into our own source tree, so the runtime/encoder has
 *     ZERO dependencies and can run inside any modern browser, Web Worker, or Node.
 *
 * Run:  npm run gen:qrtables        (from the repo root)
 * Verify output matches the currently checked-in file:
 *        npm run gen:qrtables -- --check
 */

import { createRequire } from 'node:module';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const outFile = path.join(repoRoot, 'packages/core/src/qr/tables.ts');

const ECCode = require('qrcode/lib/core/error-correction-code');
const AlignmentPattern = require('qrcode/lib/core/alignment-pattern');
const Version = require('qrcode/lib/core/version');
const Utils = require('qrcode/lib/core/utils');

const ECLevel = require('qrcode/lib/core/error-correction-level');

const LEVELS = ['L', 'M', 'Q', 'H'];
/** qrcode's internal level sentinels ({ bit: n }), keyed by our string levels. */
const LEVEL_SENTINEL = { L: ECLevel.L, M: ECLevel.M, Q: ECLevel.Q, H: ECLevel.H };

/** RS block table: number of blocks for (version, level) -> EC codewords per block. */
function blockTable(version, level) {
  const sentinel = LEVEL_SENTINEL[level];
  const blocks = ECCode.getBlocksCount(version, sentinel);
  const totalEc = ECCode.getTotalCodewordsCount(version, sentinel);
  if (totalEc % blocks !== 0) {
    throw new Error(`version ${version} level ${level}: ${totalEc} EC codewords not divisible by ${blocks} blocks`);
  }
  return { blocks, ecPerBlock: totalEc / blocks };
}

function build() {
  const symbolTotalCodewords = [0]; // index 0 unused so version === index
  const ecBlocks = [];
  const alignmentCoords = [];
  const versionInfoBits = [];
  const capacity = {}; // capacity[level][version] = max byte-mode payload bytes

  for (let v = 1; v <= 40; v++) {
    symbolTotalCodewords[v] = Utils.getSymbolTotalCodewords(v);
    alignmentCoords[v] = AlignmentPattern.getRowColCoords(v);
    versionInfoBits[v] = v >= 7 ? Version.getEncodedBits(v) : 0;
    ecBlocks[v] = {};
    for (const level of LEVELS) {
      const { blocks, ecPerBlock } = blockTable(v, level);
      ecBlocks[v][level] = { blocks, ecPerBlock };
    }
  }

  for (const level of LEVELS) {
    capacity[level] = [];
    for (let v = 1; v <= 40; v++) {
      capacity[level][v] = Version.getCapacity(v, LEVEL_SENTINEL[level]);
    }
  }

  const fmt = (n, pad = 2) => String(n).padStart(pad, ' ');
  const arr = (a) => `[${a.join(', ')}]`;

  let out = '';
  out += `/**\n`;
  out += ` * tables.ts - QR Code (ISO/IEC 18004) static tables.\n`;
  out += ` *\n`;
  out += ` * AUTO-GENERATED by tools/gen-qr-tables.mjs. Do not edit by hand.\n`;
  out += ` * Regenerate with:  npm run gen:qrtables\n`;
  out += ` *\n`;
  out += ` * Indexing convention throughout this file: arrays are 1-based by QR version\n`;
  out += ` * (index 0 is a placeholder), so \`SYMBOL_TOTAL_CODEWORDS[7]\` is version 7.\n`;
  out += ` */\n\n`;

  out += `export type EcLevel = 'L' | 'M' | 'Q' | 'H';\n\n`;
  out += `/** EC level -> integer, as encoded in the format-information bits. */\n`;
  out += `export const EC_LEVEL_BITS: Record<EcLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };\n\n`;
  out += `/** Integer -> EC level. */\n`;
  out += `export const EC_LEVEL_FROM_BITS: EcLevel[] = ['M', 'L', 'H', 'Q'];\n\n`;

  out += `/** Total codewords (data + error correction) in the symbol for each version. */\n`;
  out += `export const SYMBOL_TOTAL_CODEWORDS: number[] = ${arr(symbolTotalCodewords)};\n\n`;

  out += `export interface EcBlockGroup {\n`;
  out += `  /** Number of Reed-Solomon blocks the data area is split into. */\n`;
  out += `  blocks: number;\n`;
  out += `  /** EC codewords appended to each block. */\n`;
  out += `  ecPerBlock: number;\n`;
  out += `}\n\n`;
  out += `/**\n`;
  out += ` * Reed-Solomon block layout: EC_BLOCKS[version][level].\n`;
  out += ` * Every block in a QR symbol uses the same EC count, and the data codewords\n`;
  out += ` * are distributed as evenly as possible (the first \`remainder\` blocks get one\n`;
  out += ` * extra codeword). See reed-solomon.ts.\n`;
  out += ` */\n`;
  out += `export const EC_BLOCKS: Record<EcLevel, EcBlockGroup[]> = {\n`;
  for (const level of LEVELS) {
    out += `  ${level}: [\n`;
    out += `    { blocks: 0, ecPerBlock: 0 }, // version 0 placeholder\n`;
    for (let v = 1; v <= 40; v++) {
      const g = ecBlocks[v][level];
      out += `    { blocks: ${fmt(g.blocks)}, ecPerBlock: ${fmt(g.ecPerBlock)} }, // v${v}\n`;
    }
    out += `  ],\n`;
  }
  out += `};\n\n`;

  out += `/**\n`;
  out += ` * Alignment-pattern centre coordinates (row === column positions).\n`;
  out += ` * Every (row, col) combination is used except the three that collide with the\n`;
  out += ` * finder patterns.\n`;
  out += ` */\n`;
  out += `export const ALIGNMENT_PATTERN_COORDS: number[][] = [\n`;
  out += `  [],\n`;
  for (let v = 1; v <= 40; v++) {
    out += `  ${arr(alignmentCoords[v])}, // v${v}\n`;
  }
  out += `];\n\n`;

  out += `/**\n`;
  out += ` * 18-bit version information codeword for QR versions 7..40,\n`;
  out += ` * computed with the (18,6) Golay code and generator 0b1111100100101.\n`;
  out += ` * Versions 1..6 carry no version information block.\n`;
  out += ` */\n`;
  out += `export const VERSION_INFO_BITS: number[] = [\n`;
  out += `  0,\n`;
  for (let v = 1; v < 7; v++) out += `  0, // v${v} (no version info block)\n`;
  for (let v = 7; v <= 40; v++) out += `  0x${versionInfoBits[v].toString(16)}, // v${v}\n`;
  out += `];\n\n`;

  out += `/** Maximum payload bytes for byte mode, per level and version: CAPACITY[level][version]. */\n`;
  out += `export const BYTE_MODE_CAPACITY: Record<EcLevel, number[]> = {\n`;
  for (const level of LEVELS) {
    out += `  ${level}: [\n`;
    out += `    0,\n`;
    for (let v = 1; v <= 40; v++) {
      out += `    ${String(capacity[level][v]).padStart(4, ' ')}, // v${v} (${18 + v * 4}x${18 + v * 4} modules)\n`;
    }
    out += `  ],\n`;
  }
  out += `};\n`;

  return out;
}

const generated = build();

if (process.argv.includes('--check')) {
  if (!existsSync(outFile)) {
    console.error('tables.ts does not exist');
    process.exit(1);
  }
  const current = readFileSync(outFile, 'utf8');
  if (current !== generated) {
    console.error('tables.ts is out of date. Run: npm run gen:qrtables');
    process.exit(1);
  }
  console.log('tables.ts is up to date.');
} else {
  writeFileSync(outFile, generated);
  console.log(`wrote ${path.relative(repoRoot, outFile)} (${generated.length} bytes)`);
}
